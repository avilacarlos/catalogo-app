-- Art & Print - Catalogo de Versos V2
-- Primera migracion: tablas nuevas.
-- RLS se habilitara en una etapa posterior.
-- Requisito: public.versos.id debe ser compatible con bigint.

create table if not exists public.categorias_verso (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  slug text not null unique,
  descripcion text,
  orden integer not null default 0,
  activo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.clientes (
  id bigint generated by default as identity primary key,
  nombre text not null,
  telefono text,
  notas text,
  activo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.eventos (
  id bigint generated by default as identity primary key,
  cliente_id bigint not null references public.clientes(id),
  categoria_id bigint not null references public.categorias_verso(id),
  festejado text not null,
  slug text not null unique,
  estado text not null default 'borrador'
    check (estado in ('borrador', 'activo', 'cerrado', 'archivado')),
  notas text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.favoritos (
  id bigint generated by default as identity primary key,
  evento_id bigint not null references public.eventos(id) on delete cascade,
  verso_id bigint not null references public.versos(id),
  created_at timestamptz not null default now(),
  unique (evento_id, verso_id)
);

create table if not exists public.selecciones (
  id bigint generated by default as identity primary key,
  evento_id bigint not null unique references public.eventos(id) on delete cascade,
  verso_id bigint not null references public.versos(id),
  estado text not null default 'seleccionado'
    check (estado in ('seleccionado', 'confirmado')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_eventos_cliente_id
  on public.eventos(cliente_id);

create index if not exists idx_eventos_categoria_id
  on public.eventos(categoria_id);

create index if not exists idx_eventos_estado
  on public.eventos(estado);

create index if not exists idx_favoritos_evento_id
  on public.favoritos(evento_id);

create index if not exists idx_selecciones_evento_id
  on public.selecciones(evento_id);

create or replace function public.actualizar_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_categorias_verso_updated_at
on public.categorias_verso;

create trigger trg_categorias_verso_updated_at
before update on public.categorias_verso
for each row execute function public.actualizar_updated_at();

drop trigger if exists trg_clientes_updated_at
on public.clientes;

create trigger trg_clientes_updated_at
before update on public.clientes
for each row execute function public.actualizar_updated_at();

drop trigger if exists trg_eventos_updated_at
on public.eventos;

create trigger trg_eventos_updated_at
before update on public.eventos
for each row execute function public.actualizar_updated_at();

drop trigger if exists trg_selecciones_updated_at
on public.selecciones;

create trigger trg_selecciones_updated_at
before update on public.selecciones
for each row execute function public.actualizar_updated_at();

